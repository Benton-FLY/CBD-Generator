import {chromium} from 'playwright';
import ExcelJS from 'exceljs';
const b=await chromium.launch({headless:true});
const p=await b.newPage({acceptDownloads:true});
await p.goto('https://cbd-generator.pages.dev/#comparison');
await p.locator('input[type=file]').nth(0).setInputFiles(['reference/FLY RACING 27 MX JERSEY CBD 2025.10.17.xlsx','reference/FLY RACING 27 BMX JERSEY CBD 2025.10.17.xlsx']);
await p.locator('input[type=file]').nth(1).setInputFiles('reference/FLY RACING 28 MX BMX JERSEY CBD SHEET (내부) 2026.09.02.xlsx');
await p.getByText('2개 파일 · 16개 STYLE',{exact:true}).waitFor({timeout:60000});
await p.getByRole('button',{name:'STYLE 매칭 확정'}).click();
await p.getByRole('heading',{name:'자재 매칭 검토'}).waitFor({timeout:60000});
const event=p.waitForEvent('download');
await p.getByRole('button',{name:'비교 Excel 추출'}).last().click();
const download=await event,path=await download.path();
console.log('download',download.suggestedFilename(),'path',path);
if(!path)throw new Error('download path unavailable');
const wb=new ExcelJS.Workbook();await wb.xlsx.readFile(path);
const formulas=[];for(const ws of wb.worksheets)ws.eachRow(row=>row.eachCell(cell=>{if(typeof cell.value==='object'&&cell.value?.formula)formulas.push(cell.value.formula)}));
if(wb.worksheets.length<2||!formulas.length)throw new Error(`comparison workbook validation failed: sheets=${wb.worksheets.length} formulas=${formulas.length}`);
if(formulas.some(c=>String(c).includes('#REF!')))throw new Error('#REF! formula found');
console.log(`Cloudflare export PASS: ${wb.worksheets.length} sheets, ${formulas.length} formulas`);await b.close();
